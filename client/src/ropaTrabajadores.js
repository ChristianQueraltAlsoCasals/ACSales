export function normNombre(s) {
  return String(s || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, " ")
    .trim();
}

export function comprasDe(nombre) {
  const n = normNombre(nombre);
  if (!n) return [];
  const exactos = COMPRAS.filter((c) => normNombre(c.nombre) === n);
  if (exactos.length) return exactos;
  const tokens = n.split(" ").filter(Boolean);
  const nombres = [...new Set(COMPRAS.map((c) => normNombre(c.nombre)))];
  const candidatos = nombres.filter((cn) => {
    const ct = cn.split(" ").filter(Boolean);
    if (tokens.length < 2 || ct.length < 2) return false;
    return tokens.every((t) => ct.includes(t)) || ct.every((t) => tokens.includes(t));
  });
  if (candidatos.length !== 1) return [];
  return COMPRAS.filter((c) => normNombre(c.nombre) === candidatos[0]);
}
